from __future__ import annotations

from pants.engine.addresses import Address
from pants.engine.target import (
    COMMON_TARGET_FIELDS,
    BoolField,
    Dependencies,
    InvalidFieldException,
    MultipleSourcesField,
    StringField,
    StringSequenceField,
    Target,
    TargetGenerator,
)
from pants.util.strutil import softwrap


class DebPackagesResolveField(StringField):
    alias = "resolve"
    required = True
    help = softwrap("""
    The name of the resolve, which must be a key of `[apt].resolves`. Its lockfile is
    written by `pants generate-lockfiles --resolve=<name>`.
    """)


class DebPackagesSourcesField(StringSequenceField):
    alias = "sources"
    required = True
    help = softwrap("""
    The apt repositories to resolve against, each a sources.list line without the leading `deb`:
    `<uri> <suite> <component>...`, e.g.
    `https://snapshot.debian.org/archive/debian/20241001T000000Z bookworm main` or
    `https://snapshot.ubuntu.com/ubuntu/20241001T000000Z noble main`. Pin the URI to a
    snapshot so the lockfile can be regenerated. When several sources have the same package, the
    highest version wins; for equal versions the earlier source wins.
    """)

    @classmethod
    def compute_value(cls, raw_value, address: Address):
        value = super().compute_value(raw_value, address)
        for line in value or ():
            if len(line.split()) < 3:
                raise InvalidFieldException(
                    f"Each entry of the `{cls.alias}` field of {address} must look like "
                    f"`<uri> <suite> <component>...`, got {line!r}"
                )
        return value


class DebPackagesArchitecturesField(StringSequenceField):
    alias = "architectures"
    required = True
    help = softwrap("""
    The Debian architectures to resolve, e.g. `["amd64", "arm64"]`. Each one gets its own
    closure in the lockfile and its own generated targets.
    """)


class DebPackagesPackagesField(StringSequenceField):
    alias = "packages"
    required = True
    help = softwrap("""
    The top-level packages to resolve. Their `Pre-Depends` and `Depends` are resolved
    transitively.
    """)


class DebPackagesExcludeField(StringSequenceField):
    alias = "exclude"
    default = ()
    help = softwrap("""
    Packages treated as already installed, typically the ones the base image ships. They satisfy
    any dependency on them and are left out of the lockfile together with whatever only they
    depend on. Virtual package names are accepted too.
    """)


class DebPackagesKeyringsField(MultipleSourcesField):
    alias = "keyrings"
    expected_file_extensions = (".gpg", ".asc")
    help = softwrap("""
    OpenPGP keyrings, binary (`.gpg`) or armored (`.asc`), holding the keys the repositories sign
    their `Release` files with, e.g. the `debian-archive-keyring.gpg` of the `debian-archive-keyring`
    package or the `ubuntu-archive-keyring.gpg` of `ubuntu-keyring`. `generate-lockfiles` fails
    unless every suite's `InRelease` (or `Release` and `Release.gpg`) has a good signature from one
    of their keys. Only RSA and Ed25519 keys are supported, which is what Debian and Ubuntu use.

    Every key in the keyrings is trusted as given, whatever its expiry or revocation. Either this
    or `allow_unsigned=True` is required.
    """)


class DebPackagesAllowUnsignedField(BoolField):
    alias = "allow_unsigned"
    default = False
    help = softwrap("""
    Resolve without verifying the signatures of the repositories' `Release` files, e.g. for an
    unsigned internal repository. Can't be combined with `keyrings`.
    """)


class DebPackageArchitectureField(StringField):
    alias = "architecture"
    required = True
    help = "The Debian architecture the package is resolved for."


class DebPackagePackageField(StringField):
    alias = "package"
    required = True
    help = softwrap("""
    The requested package, as listed in `packages`. A virtual package resolves to the package that
    provides it.
    """)


class DebPackageSourcesField(MultipleSourcesField):
    # Only for codegen: it generates the `.deb` files of the package's locked closure.
    alias = "_sources"
    expected_num_files = 0


class DebPackageTarget(Target):
    alias = "deb_package"
    core_fields = (
        *COMMON_TARGET_FIELDS,
        DebPackageArchitectureField,
        DebPackagePackageField,
        DebPackageSourcesField,
    )
    help = softwrap("""
    A requested Debian package with its whole locked closure of dependencies, whose pinned `.deb`
    files are its sources. Generated by `deb_packages`; don't declare it directly.
    """)


class DebPackageGroupTarget(Target):
    alias = "deb_package_group"
    core_fields = (*COMMON_TARGET_FIELDS, Dependencies)
    help = softwrap("""
    All the requested packages of a `deb_packages` resolve for one architecture. Generated by
    `deb_packages`; don't declare it directly.
    """)


class DebPackagesTargetGenerator(TargetGenerator):
    alias = "deb_packages"
    help = softwrap("""
    Debian packages resolved from apt repository snapshots into a lockfile.

    Generates, for every architecture and requested package, a `deb_package` target named
    `<arch>/<package>` whose sources are the pinned `.deb` files of the package and its whole locked
    closure, e.g. `debs=[":bookworm#amd64/jq"]` for `oci_deb_layer`. It also generates a
    `deb_package_group` target named `<arch>` depending on all the requested packages for that
    architecture. Only requested packages get targets, so list a package in `packages` to depend
    on it. The targets come from this target's fields alone; the lockfile is read when their `.deb`
    files are needed, which fails if it's missing or out of date. A layer is for one architecture,
    so don't pass the `deb_packages` target itself.
    """)
    generated_target_cls = DebPackageTarget
    core_fields = (
        *COMMON_TARGET_FIELDS,
        DebPackagesResolveField,
        DebPackagesSourcesField,
        DebPackagesArchitecturesField,
        DebPackagesPackagesField,
        DebPackagesExcludeField,
        DebPackagesKeyringsField,
        DebPackagesAllowUnsignedField,
    )
    copied_fields = COMMON_TARGET_FIELDS
    moved_fields = ()


def targets():
    return [DebPackagesTargetGenerator, DebPackageTarget, DebPackageGroupTarget]
